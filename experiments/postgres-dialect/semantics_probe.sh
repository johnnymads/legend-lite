#!/bin/zsh
# Same expression, two engines: DuckDB (the base renderer's de-facto target) vs Postgres.
# usage: semantics_probe.sh DUCKDB_CLI PG_CONTAINER   (outside the Bazel build; experiments/ is in .bazelignore)
DUCK=$1; PG=$2
probes=(
 "int division|select 7/2"
 "neg int division|select -7/2"
 "int modulo neg|select -7 % 3"
 "int / 0|select 1/0"
 "round half (numeric)|select round(2.5)"
 "round half neg|select round(-2.5)"
 "round half (double)|select round(2.5::double precision)"
 "round 2dp|select round(2.345, 2)"
 "cast 2.7 to int|select cast(2.7 as integer)"
 "cast -2.5 to int|select cast(-2.5 as integer)"
 "bigint overflow|select 9223372036854775807 + 1"
 "power type|select power(2, 10)"
 "concat null via ||| select 'a' || NULL"
 "concat() null|select concat('a', NULL, 'b')"
 "length utf8|select length('héllo')"
 "substr from 0|select substr('hello', 0, 2)"
 "left negative|select left('abcde', -2)"
 "like default escape|select 'a_c' like 'a\\_c', 'abc' like 'a\\_c'"
 "ilike|select 'ABC' ilike 'a%'"
 "split_part negative|select split_part('a,b,c', ',', -1)"
 "regexp_replace first|select regexp_replace('aaa', 'a', 'b')"
 "tilde operator|select 'abc' ~ 'b'"
 "lpad truncates|select lpad('abcd', 2, 'x')"
 "greatest w/ null|select greatest(1, NULL, 3)"
 "order desc nulls|select string_agg(coalesce(x::text,'N'), ',' order by x desc) from (values (1),(NULL),(2)) t(x)"
 "order asc nulls|select string_agg(coalesce(x::text,'N'), ',' order by x) from (values (1),(NULL),(2)) t(x)"
 "avg(int) value|select avg(x) from (values (1),(2)) t(x)"
 "sum(int) big|select sum(x) from (values (2147483647),(1)) t(x)"
 "stddev one row|select stddev(x) from (values (1.0)) t(x)"
 "bool to int|select cast(true as integer)"
 "date + 1 month (31st)|select date '2024-01-31' + interval '1 month'"
 "date_trunc on date|select date_trunc('month', date '2024-03-15')"
 "date - date|select date '2024-03-01' - date '2024-02-01'"
 "dow sunday|select extract(dow from date '2024-01-07')"
 "isodow sunday|select extract(isodow from date '2024-01-07')"
 "week of jan 1|select extract(week from date '2021-01-01')"
 "epoch of ts|select extract(epoch from timestamp '2024-01-01 00:00:01')"
 "ts - ts|select timestamp '2024-01-02 10:00' - timestamp '2024-01-01 09:30'"
 "unquoted ident case|select x from (select 1 as \"X\") t"
 "bool_and|select bool_and(b) from (values (true),(false)) t(b)"
 "array literal|select array[1,2,3]"
 "array index 1-based|select (array[10,20,30])[1]"
 "unnest|select count(*) from unnest(array[1,2,3])"
 "string_to_array|select string_to_array('a,b', ',')"
 "array_agg order|select array_agg(x order by x desc) from (values (1),(2)) t(x)"
 "filter clause|select count(*) filter (where x > 1) from (values (1),(2)) t(x)"
 "qualify|select x from (values (1),(2)) t(x) qualify row_number() over () = 1"
 "group by all|select x, count(*) from (values (1)) t(x) group by all"
 "select exclude|select * exclude (y) from (select 1 x, 2 y) t"
 "list_transform|select list_transform([1,2], x -> x + 1)"
 "struct literal|select {'a': 1}"
 "integer // |select 7 // 2"
 "trunc numeric|select trunc(-2.7)"
 "mod float|select mod(5.5, 2)"
 "nullif|select nullif(1, 1)"
 "is distinct from|select NULL is distinct from NULL"
 "interval out|select interval '90 minutes'"
 "to_char|select to_char(date '2024-01-05', 'YYYY-MM-DD')"
 "strftime|select strftime(date '2024-01-05', '%Y-%m-%d')"
 "json ->>|select ('{\"a\":1}'::json) ->> 'a'"
)
printf '%-24s | %-34s | %s\n' probe duckdb postgres
for p in "${probes[@]}"; do
  label=${p%%|*}; sql=${p#*|}
  d=$(print -r -- "$sql;" | $DUCK -csv -noheader 2>&1 | head -1 | cut -c1-34)
  g=$(docker exec $PG psql -U postgres -tA -c "$sql" 2>&1 | head -1 | sed 's/^ERROR: */ERR: /' | cut -c1-40)
  printf '%-24s | %-34s | %s\n' "$label" "$d" "$g"
done
